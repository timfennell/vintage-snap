"""Generates app/src/main/java/app/relens/optics/LensCatalogue.kt from Vintage
Click's Lens.swift, so the lens bag stays the game's (names are fictional there).

    python3 scripts/port_lenses.py ~/Documents/splat_camera/Sources/SplatCamera/Lens.swift
"""
import os, re, sys

src = open(os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else
                              "~/Documents/splat_camera/Sources/SplatCamera/Lens.swift")).read()
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                   "app/src/main/java/app/relens/optics/LensCatalogue.kt")

INT_KEYS = {"blades"}
BOOL_KEYS = {"rearFilter"}
STRING_KEYS = {"name", "inspiredBy", "collection"}


def split_args(s):
    """Top-level comma split, strings and brackets respected."""
    out, depth, cur, i, in_str = [], 0, "", 0, False
    while i < len(s):
        c = s[i]
        if in_str:
            cur += c
            if c == "\\":
                cur += s[i + 1]; i += 1
            elif c == '"':
                in_str = False
        elif c == '"':
            in_str = True; cur += c
        elif c in "([":
            depth += 1; cur += c
        elif c in ")]":
            depth -= 1; cur += c
        elif c == "," and depth == 0:
            out.append(cur.strip()); cur = ""
        else:
            cur += c
        i += 1
    if cur.strip():
        out.append(cur.strip())
    return out


def num(v):
    v = v.strip()
    return v + "f" if re.fullmatch(r"-?\d+(\.\d+)?", v) else v


def value(k, v):
    v = v.strip()
    if k in STRING_KEYS:
        return v.replace("$", "\\$")
    if k in INT_KEYS:
        return v
    if k in BOOL_KEYS:
        return v
    if k == "movement":
        m = re.fullmatch(r"\.(tilt|shift)\((.+)\)", v)
        return f"Movement.{m.group(1).capitalize()}({num(m.group(2))})"
    if k == "projection":
        return {".rectilinear": "Projection.RECTILINEAR", ".fisheye": "Projection.FISHEYE",
                ".circularFisheye": "Projection.CIRCULAR_FISHEYE"}[v]
    return num(v)


def lens_calls(block):
    """Every Lens(...) in a Swift array literal, as Kotlin."""
    out, i = [], 0
    while True:
        j = block.find("Lens(", i)
        if j < 0:
            return out
        k, depth, in_str = j + 5, 1, False
        while depth:
            c = block[k]
            if in_str:
                if c == "\\": k += 1
                elif c == '"': in_str = False
            elif c == '"': in_str = True
            elif c == "(": depth += 1
            elif c == ")": depth -= 1
            k += 1
        args = split_args(block[j + 5:k - 1])
        kv = []
        for a in args:
            key, _, v = a.partition(":")
            kv.append(f"{key.strip()} = {value(key.strip(), v)}")
        out.append("Lens(" + ", ".join(kv) + ")")
        i = k


arrays = {}
for m in re.finditer(r"(?:private )?let (\w+): \[Lens\] = \[(.*?)\n\]", src, re.S):
    body = re.sub(r"//[^\n]*", "", m.group(2))   # drop comments (they may hold "Lens(")
    arrays[m.group(1)] = lens_calls(body)

cols = re.search(r"let lensCollections: \[LensCollection\] = \[(.*?)\n\]", src, re.S).group(1)
collections = re.findall(r'LensCollection\(name: (".*?"), about: (".*?"), lenses: (\w+)\)', cols)
added_later = re.findall(r'"([^"]+)"', re.search(r"addedLater: \[String\] = \[(.*?)\]", src, re.S).group(1))

kt = ["// Generated by scripts/port_lenses.py from Vintage Click's Lens.swift. Do not edit by hand.",
      "// Names are made up; inspiredBy says what each lens plays.", "package app.relens.optics", ""]
for name, calls in arrays.items():
    kt.append(f"private val {name}: List<Lens> = listOf(")
    kt += [f"    {c}," for c in calls]
    kt.append(")")
    kt.append("")
kt.append("val lensCollections: List<LensCollection> = listOf(")
for n, a, l in collections:
    kt.append(f"    LensCollection({n}, {a}, {l}.map {{ it.copy(collection = {n}) }}),")
kt.append(")")
kt.append("")
kt.append("/** Lenses added to a shelf after the bag's order was fixed: they go at the end (as in the game). */")
kt.append("private val addedLater = listOf(" + ", ".join(f'"{n}"' for n in added_later) + ")")
kt.append("")
kt.append("/** Every lens, in the game's bag order (a lens's index is its number). */")
kt.append("val lensBag: List<Lens> by lazy {")
kt.append("    val all = lensCollections.flatMap { it.lenses }")
kt.append("    all.filter { it.name !in addedLater } + addedLater.mapNotNull { n -> all.firstOrNull { it.name == n } }")
kt.append("}")
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write("\n".join(kt) + "\n")
print(OUT, {k: len(v) for k, v in arrays.items()})
